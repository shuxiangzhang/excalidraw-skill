#!/usr/bin/env node
/** Generate an import-free, awaitable Obsidian EA script from a diagram definition. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { iconNames } from "../assets/icons.mjs";

function fail(message) { throw new Error(message); }
function string(value, field, fallback = "") {
  if (value === undefined) return fallback;
  if (typeof value !== "string") fail(`${field} must be a string`);
  return value;
}
function integer(value, field, minimum, maximum) {
  if (!Number.isInteger(value) || value < minimum || value > maximum) {
    fail(`${field} must be an integer from ${minimum} to ${maximum}`);
  }
  return value;
}

/** Validate identities, layout, references and edge endpoints before writing a script. */
export function normalizeGraph(input) {
  if (!input || typeof input !== "object" || Array.isArray(input)) fail("Expected a JSON object");
  const title = string(input.title, "title").trim();
  if (!title) fail("title must not be empty");
  if (!Array.isArray(input.nodes) || !input.nodes.length) fail("nodes must be a nonempty array");
  if (!Array.isArray(input.edges)) fail("edges must be an array of explicit relationships");
  const columns = integer(input.columns ?? Math.min(3, input.nodes.length), "columns", 1, 8);
  const ids = new Set();
  const positions = new Set();
  const nodes = input.nodes.map((node, index) => {
    if (!node || typeof node !== "object" || Array.isArray(node)) fail(`Invalid node ${index}`);
    const id = string(node.id, `nodes[${index}].id`).trim();
    if (!id || ids.has(id)) fail(`Missing or duplicate node id: ${id}`);
    ids.add(id);
    const label = string(node.title, `node ${id} title`).trim();
    if (!label) fail(`Node ${id} must have a title`);
    const row = integer(node.row ?? Math.floor(index / columns), `node ${id} row`, 0, 1000);
    const automatic = index % columns;
    const column = integer(node.column ?? (row % 2 ? columns - automatic - 1 : automatic),
      `node ${id} column`, 0, columns - 1);
    const position = `${row}:${column}`;
    if (positions.has(position)) fail(`Two nodes occupy row/column ${position}`);
    positions.add(position);
    const icon = node.icon ?? "code";
    if (!iconNames.includes(icon)) fail(`Unknown icon ${icon}; choose ${iconNames.join(", ")}`);
    const sources = node.sources ?? [];
    if (!Array.isArray(sources) || sources.some(source => typeof source !== "string")) {
      fail(`Node ${id} sources must be an array of strings`);
    }
    if (node.color !== undefined && !/^#[0-9a-f]{6}$/i.test(node.color)) fail(`Invalid color for ${id}`);
    return { id, title: label, description: string(node.description, `${id}.description`),
      command: string(node.command, `${id}.command`), sources, icon, row, column,
      color: node.color ?? ["#1d4ed8", "#7e22ce", "#047857", "#b45309"][row % 4] };
  });
  const edges = input.edges.map((edge, index) => {
    if (!edge || typeof edge !== "object") fail(`Invalid edge ${index}`);
    if (!ids.has(edge.from) || !ids.has(edge.to)) fail(`Edge ${index} refers to an unknown node`);
    if (edge.from === edge.to) fail(`Edge ${index}: represent a loop using two distinct nodes`);
    const kind = edge.kind ?? "flow";
    if (!["flow", "feedback", "optional"].includes(kind)) fail(`Unknown edge kind: ${kind}`);
    return { from: edge.from, to: edge.to, label: string(edge.label, `edge ${index} label`), kind };
  });
  const rowTitles = input.rowTitles ?? [];
  if (!Array.isArray(rowTitles)) fail("rowTitles must be an array");
  const titledRows = new Set();
  const normalizedTitles = rowTitles.map(item => {
    const row = integer(item.row, "rowTitles.row", 0, 1000);
    if (!nodes.some(node => node.row === row) || titledRows.has(row)) fail(`Invalid row title: ${row}`);
    titledRows.add(row);
    return { row, title: string(item.title, "rowTitles.title") };
  });
  return { title, subtitle: string(input.subtitle, "subtitle"), columns,
    cardWidth: integer(input.cardWidth ?? 380, "cardWidth", 280, 600),
    numbered: input.numbered !== false, nodes, edges, rowTitles: normalizedTitles,
    footer: string(input.footer, "footer", "Editable Excalidraw workflow") };
}

/** Inline trusted runtime assets and JSON data, with no npm or vault imports at runtime. */
export function generateScript(input) {
  const graph = normalizeGraph(input);
  const icons = readFileSync(new URL("../assets/icons.mjs", import.meta.url), "utf8")
    .replace(/^export (?=(?:async )?(?:function|const))/gm, "");
  const runtime = readFileSync(new URL("../assets/runtime.js", import.meta.url), "utf8");
  // Parsing quoted JSON preserves data such as quotes, backticks and prototype-like keys.
  const data = JSON.stringify(JSON.stringify(graph));
  const script = `/* Generated by the Excalidraw skill. Native editable elements; no runtime imports. */\n` +
    `await (async () => {\nconst diagram = JSON.parse(${data});\n${icons}\n${runtime}\n` +
    `await renderDiagram(ea, diagram);\n})().catch(error => { new ea.obsidian.Notice(String(error.message ?? error)); throw error; });\n`;
  const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
  new AsyncFunction("ea", "utils", script);
  return script;
}

function main() {
  const args = process.argv.slice(2);
  if (args.includes("--help") || !args.length) {
    console.log("Usage: node generate_script.mjs definition.json output.md [--force]");
    return;
  }
  const paths = args.filter(arg => arg !== "--force");
  if (paths.length !== 2 || paths.some(arg => arg.startsWith("--"))) fail("Expected input.json output.md [--force]");
  if (!paths[1].endsWith(".md")) fail("Output must be a Script Engine .md file");
  const input = JSON.parse(readFileSync(resolve(paths[0]), "utf8"));
  writeFileSync(resolve(paths[1]), generateScript(input), { flag: args.includes("--force") ? "w" : "wx" });
  console.log(`Generated ${resolve(paths[1])}: ${input.nodes.length} nodes, ${input.edges.length} edges.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
